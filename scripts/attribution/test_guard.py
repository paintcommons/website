import importlib.util
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location('guard', Path(__file__).with_name('guard.py'))
guard = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(guard)
SCRIPT = Path(guard.__file__).resolve()


class GuardTest(unittest.TestCase):
    def test_credits_and_normal_discussion(self):
        for text in ['Co-authored-by: Codex <codex@openai.com>', 'Co-Authored-By: Claude Opus <noreply@anthropic.com>', '🤖 Generated with [Claude Code](https://claude.ai)', 'Written by an AI assistant', 'Generated by OpenAI Codex']:
            self.assertTrue(guard.text_errors(text), text)
        for text in ['Fix agent permissions', 'Reject Codex attribution', 'Document how Claude connects', 'Generated by the catalog build script', 'Co-authored-by: Jim Thomas <8242332+Left47@users.noreply.github.com>']:
            self.assertFalse(guard.text_errors(text), text)

    @patch.dict(guard.POLICY, {'authorEmails': ['8242332+left47@users.noreply.github.com', '41898282+github-actions[bot]@users.noreply.github.com']})
    def test_identities(self):
        self.assertIsNone(guard.identity_error('Jim Thomas <8242332+Left47@users.noreply.github.com>'))
        self.assertIsNone(guard.identity_error('GitHub <noreply@github.com>', True))
        self.assertIsNone(guard.identity_error('github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>'))
        self.assertTrue(guard.identity_error('Unknown agent <new-agent@example.org>'))
        self.assertTrue(guard.identity_error('Codex <8242332+Left47@users.noreply.github.com>'))
        with patch.dict(guard.POLICY, {'authorEmails': None}):
            self.assertIsNone(guard.identity_error('Community contributor <human@example.org>'))
            self.assertTrue(guard.identity_error('Claude <noreply@anthropic.com>'))

    def test_pr_metadata_is_data_only(self):
        with tempfile.TemporaryDirectory() as folder:
            event_path = Path(folder) / 'event.json'
            event_path.write_text(json.dumps({'pull_request': {
                'title': '$(touch /tmp/must-not-run)',
                'body': 'Generated with Codex',
                'user': {'login': 'Left47'},
                'base': {'sha': 'a' * 40}, 'head': {'sha': 'b' * 40}}}))
            with patch.dict(os.environ, {'GITHUB_EVENT_PATH': str(event_path)}), patch.object(guard, 'git') as git_mock, patch.object(guard.subprocess, 'run') as object_check, patch.object(guard, 'check_commits', return_value=[]) as commits:
                object_check.return_value.returncode = 1
                self.assertTrue(guard.ci())
                git_mock.assert_called_once_with('fetch', '--no-tags', 'origin', 'b' * 40)
                commits.assert_called_once_with('a' * 40, 'b' * 40)

    def test_shared_install_preserves_existing_hooks(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            home = root / 'home'
            home.mkdir()
            repo = root / 'repo'
            repo.mkdir()
            env = {**os.environ, 'HOME': str(home), 'GIT_CONFIG_NOSYSTEM': '1', 'GIT_AUTHOR_NAME': 'Jim Thomas', 'GIT_AUTHOR_EMAIL': '8242332+Left47@users.noreply.github.com', 'GIT_COMMITTER_NAME': 'Jim Thomas', 'GIT_COMMITTER_EMAIL': '8242332+Left47@users.noreply.github.com'}
            def run(*args, **kwargs):
                return subprocess.run(args, cwd=repo, env=env, text=True, capture_output=True, **kwargs)
            result = run('python3', str(SCRIPT.with_name('install.py')), '--global')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(run('git', 'init', '-q').returncode, 0)
            original = repo / '.git/hooks/commit-msg'
            original.write_text('#!/bin/sh\necho chained > chained-marker\n')
            original.chmod(0o755)
            result = run('git', 'commit', '--allow-empty', '-m', 'Good change')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertTrue((repo / 'chained-marker').exists())
            result = run('git', 'commit', '--allow-empty', '-m', 'Change\n\nGenerated with Claude')
            self.assertNotEqual(result.returncode, 0)
            prepush = repo / '.git/hooks/pre-push'
            prepush.write_text('#!/bin/sh\ncat > push-input\n')
            prepush.chmod(0o755)
            data = 'refs/heads/main ' + '0' * 40 + ' refs/heads/main ' + 'a' * 40 + '\n'
            result = run(str(home / '.config/git/attribution-guard/pre-push'), 'origin', 'unused', input=data)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual((repo / 'push-input').read_text(), data)

    def test_real_hooks_push_and_ranges(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            env = {**os.environ, 'GIT_AUTHOR_NAME': 'Jim Thomas', 'GIT_AUTHOR_EMAIL': '8242332+Left47@users.noreply.github.com', 'GIT_COMMITTER_NAME': 'Jim Thomas', 'GIT_COMMITTER_EMAIL': '8242332+Left47@users.noreply.github.com'}
            def run(*args, **kwargs):
                return subprocess.run(args, cwd=root, env=env, text=True, capture_output=True, **kwargs)
            def git(*args):
                result = run('git', *args)
                self.assertEqual(result.returncode, 0, result.stderr)
                return result.stdout.strip()
            git('init', '-q')
            hooks = root / 'hooks'
            hooks.mkdir()
            hook = hooks / 'commit-msg'
            hook.write_text(f'#!/bin/sh\nexec python3 "{SCRIPT}" commit-msg "$@"\n')
            hook.chmod(0o755)
            git('config', 'core.hooksPath', str(hooks))
            git('commit', '--allow-empty', '-m', 'Initial change')
            base = git('rev-parse', 'HEAD')
            result = run('git', 'commit', '--allow-empty', '-m', 'Add change\n\nCo-authored-by: Codex <codex@openai.com>')
            self.assertNotEqual(result.returncode, 0)
            result = run('git', '-c', 'user.name=Codex', 'commit', '--allow-empty', '--author=Codex <codex@openai.com>', '-m', 'Add change')
            self.assertNotEqual(result.returncode, 0)
            # Bypassing commit-msg still cannot bypass the outgoing commit check.
            git('-c', 'core.hooksPath=/dev/null', 'commit', '--allow-empty', '-m', 'Bad credit\n\nCo-authored-by: Codex <codex@openai.com>')
            head = git('rev-parse', 'HEAD')
            result = run('python3', str(SCRIPT), 'range', base, head)
            self.assertNotEqual(result.returncode, 0)
            result = run('python3', str(SCRIPT), 'pre-push', 'origin', input=f'refs/heads/main {head} refs/heads/main {base}\n')
            self.assertNotEqual(result.returncode, 0)
            git('update-ref', 'refs/remotes/origin/main', base)
            result = run('python3', str(SCRIPT), 'pre-push', 'origin', input=f'refs/heads/new {head} refs/heads/new {"0" * 40}\n')
            self.assertNotEqual(result.returncode, 0)
            result = run('python3', str(SCRIPT), 'pre-push', 'origin', input=f'refs/heads/main {"0" * 40} refs/heads/main {head}\n')
            self.assertEqual(result.returncode, 0, result.stderr)
            git('reset', '--hard', base)
            git('commit', '--allow-empty', '-m', 'Good change')
            good = git('rev-parse', 'HEAD')
            result = run('python3', str(SCRIPT), 'range', base, good)
            self.assertEqual(result.returncode, 0, result.stderr)
            result = run('python3', str(SCRIPT), 'range', 'f' * 40, good)
            self.assertNotEqual(result.returncode, 0)


if __name__ == '__main__':
    unittest.main()
